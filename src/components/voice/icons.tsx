/** Work item type glyphs, matched loosely by name so custom process types still get one. */
export function TypeIcon({ type, size = 14 }: { type: string; size?: number }) {
  const t = type.toLowerCase();
  if (t === "bug" || t === "impediment" || t === "issue")
    return (
      <Svg size={size}>
        <rect x="7" y="7" width="10" height="13" rx="5" />
        <path d="M12 11v9M4 13h3M17 13h3M5 8l2.5 2M19 8l-2.5 2M5 19l2.5-2M19 19l-2.5-2M9 7a3 3 0 0 1 6 0" />
      </Svg>
    );
  if (t === "task")
    return (
      <Svg size={size}>
        <rect x="4" y="4" width="16" height="16" rx="4" />
        <path d="M8.5 12l2.5 2.5 4.5-5" />
      </Svg>
    );
  if (t === "epic")
    return (
      <Svg size={size}>
        <path d="M13 3L5 13h6l-1 8 8-10h-6l1-8z" />
      </Svg>
    );
  if (t === "feature" || t === "initiative")
    return (
      <Svg size={size}>
        <path d="M5 21V4M5 4h11l-2 4 2 4H5" />
      </Svg>
    );
  return (
    <Svg size={size}>
      <path d="M6 4h12v16l-6-4-6 4V4z" />
    </Svg>
  );
}
